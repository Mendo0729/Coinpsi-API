const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {once}=require("node:events");
test("knowledge HTTP integration against disposable PostgreSQL", {skip:process.env.KNOWLEDGE_INTEGRATION!=="1"}, async t=>{
  assert.match(process.env.DATABASE_URL||"",/^postgresql:\/\/[^@]+@(?:127\.0\.0\.1|localhost):5432\/coinpsi_test$/);
  process.env.JWT_SECRET="integration-test-secret-not-for-production";
  process.env.ADMIN_ORIGIN="http://localhost:3001";
  process.env.LANDING_ORIGIN="http://localhost:3000";
  const pool=require("../src/config/database");
  t.after(()=>pool.end());
  await pool.query(fs.readFileSync(path.join(__dirname,"fixtures/knowledge-legacy.sql"),"utf8"));
  await pool.query(fs.readFileSync(path.join(__dirname,"../migrations/2026-11-24-knowledge-library.sql"),"utf8"));
  const legacy=await pool.query("SELECT status FROM coinpsi.knowledge_posts WHERE slug='legacy'");
  assert.equal(legacy.rows[0].status,"draft");
  const columns=await pool.query("SELECT column_name FROM information_schema.columns WHERE table_schema='coinpsi' AND table_name='knowledge_posts'");
  assert.ok(!columns.rows.some(x=>x.column_name==="content"));
  const app=require("../src/app");
  const server=app.listen(0,"127.0.0.1");await once(server,"listening");t.after(()=>new Promise(r=>server.close(r)));
  const root="http://127.0.0.1:"+server.address().port+"/api/v1";
  const jwt=require("jsonwebtoken");
  const token=jwt.sign({role:"admin"},process.env.JWT_SECRET,{subject:"42",issuer:"coinpsi-api",audience:"coinpsi-admin",expiresIn:"1h"});
  async function call(url,method="GET",body,auth=false,origin="http://localhost:3000"){
   const res=await fetch(root+url,{method,redirect:"manual",headers:{Origin:origin,...(auth?{Authorization:"Bearer "+token}:{}),...(body?{"Content-Type":"application/json"}:{})},...(body?{body:JSON.stringify(body)}:{})});
   const data=res.headers.get("content-type")?.includes("json")?await res.json():null;return {status:res.status,data,headers:res.headers};
  }
  const admin="/admin/knowledge",pub="/knowledge";
  const payload={title:"Salud mental",summary:"Resumen de prueba",authorName:"Autor de prueba",categoryId:"1",driveUrl:"https://drive.google.com/file/d/abcdefghijk/view",documentType:"research",keywords:["bienestar"],publicationDate:"2026-11-24",status:"draft"};
  assert.equal((await call(admin+"/posts","POST",payload)).status,401);
  assert.equal((await call(admin+"/posts","POST",{...payload,driveUrl:"https://evil.test/file/d/abcdefghijk/view"},true)).status,400);
  const created=await call(admin+"/posts","POST",payload,true,"http://localhost:3001");assert.equal(created.status,201,JSON.stringify(created.data));
  const post=created.data.post;assert.equal(post.driveFileId,"abcdefghijk");
  const detail=pub+"/catalog/"+post.slug;
  assert.equal((await call(detail)).status,404);
  assert.equal((await call(detail+"/download")).status,404);
  assert.equal((await call(detail+"/view","POST")).status,404);
  const updated=await call(admin+"/posts/"+post.id,"PATCH",{...payload,status:"published"},true);assert.equal(updated.status,200,JSON.stringify(updated.data));
  assert.equal(updated.data.post.driveUrl,payload.driveUrl);
  const catalog=await call(pub+"/catalog?search=bienestar&category=psicologia&year=2026&type=research&page=1&limit=12");
  assert.equal(catalog.status,200);assert.equal(catalog.data.total,1);assert.equal(catalog.data.posts[0].slug,post.slug);
  assert.equal(catalog.headers.get("access-control-allow-origin"),"http://localhost:3000");
  assert.equal((await call(pub+"/catalog?limit=51")).status,400);
  assert.equal((await call(pub+"/catalog?search=nonexistent")).data.total,0);
  assert.equal((await call(pub+"/categories")).data.categories.length,1);
  assert.equal((await call(detail)).status,200);
  assert.equal((await call(detail+"/view","POST")).status,204);
  const download=await call(detail+"/download");assert.equal(download.status,302);assert.equal(new URL(download.headers.get("location")).hostname,"drive.google.com");
  assert.equal((await call(admin+"/selection","POST",{postIds:[String(post.id)]},true)).status,200);
  assert.equal((await call(pub+"/posts")).data.posts.length,1);
  const list=await call(admin+"/posts","GET",null,true);const counted=list.data.posts.find(p=>p.slug===post.slug);
  assert.equal(Number(counted.viewsCount),1);assert.equal(Number(counted.downloadsCount),1);
  assert.equal((await call(admin+"/posts/"+post.id,"PATCH",{...payload,status:"archived"},true)).status,200);
  assert.equal((await call(detail)).status,404);assert.equal((await call(pub+"/posts")).data.posts.length,0);
  assert.equal((await call(admin+"/posts/"+post.id,"DELETE",null,true)).status,200);
});
